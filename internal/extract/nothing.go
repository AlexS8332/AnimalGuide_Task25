// Nothing — в реплике заведомо нечего извлекать: это вопрос о животном, в
// котором нет ни слова о самом человеке, о форме ответа, о подборке и
// ни одного решения. Такой вопрос не звать извлекателем — минус запрос к
// модели на каждом ходе «а чем она питается?».
//
// Почему это не дыра:
//   - профиль правится только цитатой из реплики (П-6), а у слов формы
//     («коротко», «без эмодзи», «таблицей», «на ты») здесь свои маркеры;
//   - память — о человеке и подборке: без «я», «мне», «мой», «мы», «наш» и
//     без слов подборки её правкам взяться неоткуда;
//   - карточка фактов на таких ходах получала только «тема: рысь, питание» —
//     то, что код и так выводит из карточек пути (← текущая, прочитанные
//     разделы) и кладёт в блок фактов (ИП-6: выводимое не хранится);
//   - память задачи (v25) меняется только словами человека о разговоре:
//     цель («для доклада», «хочу сравнить», «помоги выбрать»), уточнение
//     («для 5 класса», «только Азия»), ограничение («без латыни»), термин
//     («я имел в виду ирбиса», «значит, барс — это ирбис?») и смена задачи
//     («давай теперь…», «вместо этого…»). У каждого такого поворота здесь
//     свой маркер (группа «задача разговора» в personStems, слова «цель» и «давай», «теперь», «только», «я»);
//     вопрос о животном без них цель не ставит — так велит и промпт;
//   - утверждение, просьба и согласие («Хорошо, план утверждаю.», «Дальше.»)
//     вопросом не считаются и уходят извлекателю как раньше;
//   - напоминание о разговоре без правок («Напомни, какая у нас цель и что
//     мы решили») — тоже «нечего»: отвечают на него по памяти задачи, а
//     правки в нём нет (reminder).
//
// Правило намеренно осторожное: любое совпадение — зовём. Ошибка в сторону
// «позвали зря» стоит запроса, в сторону «не позвали» — потерянной правки.
func Nothing(text string) bool {
	text = strings.TrimSpace(text)
	if reminder(text) {
		return true
	}
	if text == "" || !strings.HasSuffix(strings.TrimRight(text, " )»\""), "?") {
		return false
	}
	// Вопрос — одно предложение: «Я учитель. Где живёт рысь?» уже не
	// просто вопрос.
	body := strings.TrimRight(text, "?!. )»\"")
	if strings.ContainsAny(body, ".!?") {
		return false
	}
	low := strings.ReplaceAll(strings.ToLower(text), "ё", "е")
	words := strings.FieldsFunc(low, func(r rune) bool { return !unicode.IsLetter(r) && r != '-' })
	for _, w := range words {
		if personWords[w] {
			return false
		}
		for _, stem := range personStems {
			if strings.HasPrefix(w, stem) {
				return false
			}
		}
	}
	return true
}

