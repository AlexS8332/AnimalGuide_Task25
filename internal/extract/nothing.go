// reminder — просьба напомнить, о чём разговор: «Напомни, какая у нас
// цель и что мы решили», «Что мы решили?». Ответ на неё — по памяти
// задачи, правок в ней нет, и извлекатель на таком ходе (живой прогон: три
// контрольные реплики в каждом сценарии) — запрос впустую. Условия:
//   - одно предложение (вторая фраза может нести правку: «Напомни цель.
//     Давай теперь про ирбиса»);
//   - начинается с «напомни» или спрашивает «что мы решили / какая у нас
//     цель / о чём договорились»;
//   - речь о разговоре: есть слово цели, решения или договорённости;
//   - нет ни одного маркера правки (reminderEdits) и слов о человеке
//     («Напомни, как меня зовут?» — вопрос к памяти о человеке, его
//     извлекатель видит как раньше).
func reminder(text string) bool {
	body := strings.TrimRight(text, "?!. )»\"")
	if body == "" || strings.ContainsAny(body, ".!?;") {
		return false
	}
	low := strings.ReplaceAll(strings.ToLower(body), "ё", "е")
	words := strings.FieldsFunc(low, func(r rune) bool { return !unicode.IsLetter(r) && r != '-' })
	if len(words) == 0 {
		return false
	}
	asks := words[0] == "напомни" || words[0] == "напомните"
	about := false
	for _, w := range words {
		if reminderEdits[w] {
			return false
		}
		for _, stem := range reminderEditStems {
			if strings.HasPrefix(w, stem) {
				return false
			}
		}
		for _, stem := range reminderTopics {
			if strings.HasPrefix(w, stem) {
				about = true
			}
		}
	}
	if !asks {
		// Без «напомни» — только вопрос «что мы решили», «какая у нас цель».
		asks = strings.HasSuffix(strings.TrimSpace(text), "?") &&
			(strings.Contains(low, "что мы") || strings.Contains(low, "у нас цель") || strings.Contains(low, "о чем мы"))
	}
	return asks && about
}

